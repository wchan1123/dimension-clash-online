import test from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {setTimeout as delay} from 'node:timers/promises';
import {io} from 'socket.io-client';
const req=(s,event,data={})=>new Promise((resolve,reject)=>s.timeout(5000).emit(event,data,(err,r)=>err?reject(err):resolve(r)));
test('one draw OR one action, target pointing, counter validation, spectator event', {timeout:30000}, async t=>{
 const port=49000+(process.pid%9000),url='http://127.0.0.1:'+port;
 const child=spawn(process.execPath,['server.js'],{cwd:process.cwd(),env:{...process.env,PORT:String(port),NODE_ENV:'test'},stdio:'ignore'});t.after(()=>child.kill('SIGTERM'));
 let ready=false;for(let i=0;i<90;i++){try{const r=await fetch(url+'/api/cards');if(r.ok){ready=true;break}}catch{}await delay(70)}assert.equal(ready,true);
 const connect=async()=>{const s=io(url,{transports:['websocket'],forceNew:true,reconnection:false});await new Promise((ok,no)=>{s.once('connect',ok);s.once('connect_error',no)});t.after(()=>s.disconnect());return s};
 const a=await connect(),b=await connect();let sa,sb;
 a.on('state',v=>sa=v);b.on('state',v=>sb=v);
 const room=await req(a,'create',{name:'Alice'});assert.equal(room.ok,true);
 const other=await req(b,'join',{code:room.code,name:'Bob'});assert.equal(other.ok,true);
 assert.equal((await req(a,'start')).ok,true);
 assert.equal((await req(a,'draw',{count:2})).ok,false,'basic draw cannot grant multiple cards');
 assert.equal((await req(a,'draw',{count:1})).ok,true);
 assert.equal((await req(a,'draw',{count:1})).ok,false,'second draw must be denied');
 assert.equal((await req(a,'testGrant',{cards:['007','070']})).ok,true);
 assert.equal((await req(a,'announce',{cardId:'007',targetId:other.token})).ok,false,'invalid target must be rejected');
 assert.equal((await req(a,'announce',{cardId:'007',targetId:sb.me})).ok,false,'cannot play action after drawing');
 assert.equal((await req(a,'next')).ok,true);
 assert.equal((await req(b,'draw',{count:1})).ok,true);
 assert.equal((await req(b,'draw',{count:5})).ok,false);
 assert.equal((await req(b,'next')).ok,true);
 assert.equal((await req(a,'announce',{cardId:'007',targetId:sb.me})).ok,true);
 await delay(100);
 assert.equal(sb.pending.targetId,sb.me);
 assert.equal(sb.actionEvent.targetId,sb.me);
 assert.match(sb.actionEvent.label,/Bob/);
 assert.equal((await req(a,'draw',{count:1})).ok,false,'no drawing during priority');
 assert.equal((await req(b,'react',{choice:'pass'})).ok,true);
});
